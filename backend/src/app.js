require('dotenv').config();
const express = require('express'); const cors = require('cors'); const errorHandler = require('./middlewares/errorHandler'); const { success } = require('./utils/http');
const app = express();
app.disable('x-powered-by');
app.use(cors({ origin: process.env.CORS_ORIGIN ? process.env.CORS_ORIGIN.split(',').map((v)=>v.trim()) : true }));
app.use(express.json({ limit: '1mb' })); app.use(express.urlencoded({ extended: false }));
app.get('/api/health', (req,res)=>success(res,{service:'backend-buku-induk',status:'ready'}));
app.use('/api/auth', require('./routes/authRoutes'));
app.use('/api/users', require('./routes/userRoutes'));
app.use('/api/kelas', require('./routes/kelasRoutes'));
app.use('/api/guru', require('./routes/guruRoutes'));
app.use('/api/dashboard', require('./routes/dashboardRoutes'));
app.use('/api/siswa', require('./routes/siswaRoutes'));
app.use('/api/pengajuan', require('./routes/pengajuanRoutes'));
app.use('/api/presensi', require('./routes/presensiRoutes'));
app.use('/api/jadwal', require('./routes/jadwalRoutes'));
app.use('/api/rapor', require('./routes/raporRoutes'));
app.use('/api/portal', require('./routes/portalRoutes'));
app.use('/api/buku-induk', require('./routes/pdfRoutes'));
app.get('/api/system/backup-sql', require('./middlewares/authMiddleware'), require('./middlewares/roleMiddleware').authorizeRoles('OPERATOR'), require('./utils/http').asyncHandler(require('./controllers/pdfController').backupSql));
app.use((req,res)=>res.status(404).json({status:'error',message:'Endpoint tidak ditemukan.'}));
app.use(errorHandler);
module.exports = app;
